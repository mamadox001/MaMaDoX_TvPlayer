#!/usr/bin/env bash
# Builds a signed IPTV Player APK without Gradle:
#   web UI (esbuild) -> resources (aapt) -> Java (javac) -> dex (dx) -> zipalign -> apksigner
# Needs: node, aapt, javac (8+), dalvik-exchange (dx), zipalign, apksigner, keytool,
# and the Android API 23 platform jar.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"
AJ="${ANDROID_JAR:-/usr/lib/android-sdk/platforms/android-23/android.jar}"
DX="${DX:-dalvik-exchange}"
OUT="$ROOT/build"
KEYS="$ROOT/android/keys"
MANIFEST="$ROOT/android/AndroidManifest.xml"

VERSION="$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' "$MANIFEST")"
CODE="$(sed -n 's/.*android:versionCode="\([^"]*\)".*/\1/p' "$MANIFEST")"
STAMP="$(date -u +%Y%m%d.%H%M)"
APK="$OUT/IPTV-Player-$VERSION.apk"

echo "== IPTV Player $VERSION ($CODE), build $STAMP"
rm -rf "$OUT"
mkdir -p "$OUT/gen/com/iptvplayer/tv" "$OUT/stubs" "$OUT/classes"

echo "== web interface"
node web/build.mjs

cat > "$OUT/gen/com/iptvplayer/tv/BuildInfo.java" <<EOF
package com.iptvplayer.tv;
/** Generated by build.sh */
final class BuildInfo {
    static final String VERSION = "$VERSION";
    static final String BUILD = "$STAMP";
}
EOF

echo "== resources"
# resources.arsc stays uncompressed: required for apps that target Android 11+
aapt package -f -m \
  -M "$MANIFEST" -S android/res -A android/assets -I "$AJ" \
  -J "$OUT/gen" -F "$OUT/unsigned.apk" -0 arsc \
  --min-sdk-version 21 --target-sdk-version 35

echo "== java"
JFLAGS=(-source 8 -target 8 -encoding UTF-8 -nowarn -Xlint:-options -bootclasspath "$AJ")
# compile-only stubs for classes newer than the API 23 jar (never packaged)
javac "${JFLAGS[@]}" -d "$OUT/stubs" $(find android/stubs -name '*.java')
javac "${JFLAGS[@]}" -cp "$AJ:$OUT/stubs" -d "$OUT/classes" \
  $(find android/src android/core "$OUT/gen" -name '*.java')

echo "== dex"
"$DX" --dex --min-sdk-version=21 --output="$OUT/classes.dex" "$OUT/classes"
(cd "$OUT" && aapt add -f unsigned.apk classes.dex >/dev/null)

echo "== align + sign"
zipalign -f -p 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"
if [ ! -f "$KEYS/release.p12" ]; then
  mkdir -p "$KEYS"
  PASS="$(head -c 18 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 20)"
  keytool -genkeypair -storetype PKCS12 -keystore "$KEYS/release.p12" \
    -storepass "$PASS" -keypass "$PASS" -alias iptvplayer \
    -keyalg RSA -keysize 3072 -validity 12000 -dname "CN=IPTV Player" 2>/dev/null
  printf 'KEYSTORE=release.p12\nALIAS=iptvplayer\nPASSWORD=%s\n' "$PASS" > "$KEYS/signing.txt"
  echo "   new signing key in android/keys (keep it: updates must be signed with the same key)"
fi
PASS="$(sed -n 's/^PASSWORD=//p' "$KEYS/signing.txt")"
apksigner sign --ks "$KEYS/release.p12" --ks-pass "pass:$PASS" --ks-key-alias iptvplayer \
  --min-sdk-version 21 --v1-signing-enabled true --v2-signing-enabled true --v3-signing-enabled true \
  --out "$APK" "$OUT/aligned.apk"
apksigner verify --min-sdk-version 21 "$APK"
rm -f "$OUT/unsigned.apk" "$OUT/aligned.apk" "$APK.idsig"

echo "== done: $APK ($(du -k "$APK" | cut -f1) KB)"
