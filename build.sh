#!/usr/bin/env bash
# Builds the signed MaMaDoX TvPlayer APKs (TV and phone) without Gradle:
#   web UI (esbuild) -> resources (aapt) -> Java (javac) -> dex (dx) -> zipalign -> apksigner
# Needs: node, aapt, javac (8+), dalvik-exchange (dx), zipalign, apksigner, keytool,
# and the Android API 23 platform jar.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"
AJ="${ANDROID_JAR:-/usr/lib/android-sdk/platforms/android-23/android.jar}"
DX="${DX:-dalvik-exchange}"
OUT="$ROOT/build"
KEYS="$ROOT/android/keys"
MANIFEST="$ROOT/android/AndroidManifest.xml"

VERSION="$(sed -n 's/.*android:versionName="\([^"]*\)".*/\1/p' "$MANIFEST")"
CODE="$(sed -n 's/.*android:versionCode="\([^"]*\)".*/\1/p' "$MANIFEST")"
STAMP="$(date -u +%Y%m%d.%H%M)"

echo "== MaMaDoX TvPlayer $VERSION ($CODE), build $STAMP"
rm -rf "$OUT"
mkdir -p "$OUT/stubs"

if [ ! -f "$KEYS/release.p12" ]; then
  mkdir -p "$KEYS"
  NEWPASS="$(head -c 18 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 20)"
  keytool -genkeypair -storetype PKCS12 -keystore "$KEYS/release.p12" \
    -storepass "$NEWPASS" -keypass "$NEWPASS" -alias iptvplayer \
    -keyalg RSA -keysize 3072 -validity 12000 -dname "CN=MaMaDoX TvPlayer" 2>/dev/null
  printf 'KEYSTORE=release.p12\nALIAS=iptvplayer\nPASSWORD=%s\n' "$NEWPASS" > "$KEYS/signing.txt"
  echo "   new signing key in android/keys (keep it: updates must be signed with the same key)"
fi
PASS="$(sed -n 's/^PASSWORD=//p' "$KEYS/signing.txt")"

JFLAGS=(-source 8 -target 8 -encoding UTF-8 -nowarn -Xlint:-options -bootclasspath "$AJ")
# compile-only stubs for classes newer than the API 23 jar (never packaged)
javac "${JFLAGS[@]}" -d "$OUT/stubs" $(find android/stubs -name '*.java')

# flavor <name> <apk name> <manifest> <assets dir> <mobile: true|false> <target sdk> [extra aapt options]
flavor() {
  local name="$1" apk="$OUT/$2-$VERSION.apk" man="$3" assets="$4" mobile="$5" target="$6"
  shift 6
  local w="$OUT/work-$name"
  echo "== $name: resources"
  mkdir -p "$w/gen/com/iptvplayer/tv" "$w/classes"
  printf 'package com.iptvplayer.tv;\n/** Generated by build.sh */\nfinal class BuildInfo {\n    static final String VERSION = "%s";\n    static final String BUILD = "%s";\n    static final boolean MOBILE = %s;\n}\n' \
    "$VERSION" "$STAMP" "$mobile" > "$w/gen/com/iptvplayer/tv/BuildInfo.java"
  # resources.arsc stays uncompressed: required for apps that target Android 11+
  aapt package -f -m -M "$man" "$@" -S android/res -A "$assets" -I "$AJ" \
    -J "$w/gen" -F "$w/unsigned.apk" -0 arsc --min-sdk-version 21 --target-sdk-version "$target"
  echo "== $name: java + dex"
  javac "${JFLAGS[@]}" -cp "$AJ:$OUT/stubs" -d "$w/classes" $(find android/src android/core "$w/gen" -name '*.java')
  "$DX" --dex --min-sdk-version=21 --output="$w/classes.dex" "$w/classes"
  (cd "$w" && aapt add -f unsigned.apk classes.dex >/dev/null)
  echo "== $name: align + sign"
  zipalign -f -p 4 "$w/unsigned.apk" "$w/aligned.apk"
  apksigner sign --ks "$KEYS/release.p12" --ks-pass "pass:$PASS" --ks-key-alias iptvplayer \
    --min-sdk-version 21 --v1-signing-enabled true --v2-signing-enabled true --v3-signing-enabled true \
    --out "$apk" "$w/aligned.apk"
  apksigner verify --min-sdk-version 21 "$apk"
  rm -rf "$w" "$apk.idsig"
  echo "== done: $apk ($(du -k "$apk" | cut -f1) KB)"
}

echo "== web interfaces"
node web/build.mjs
node web/build.mjs --mobile

flavor tv MaMaDoX-TvPlayer android/AndroidManifest.xml android/assets false 35
flavor phone MaMaDoX-TvPlayer-Phone android/mobile/AndroidManifest.xml "$OUT/mobile-assets" true 34 \
  -S android/mobile/res --auto-add-overlay --rename-manifest-package com.mamadox.tvplayer.mobile

rm -rf "$OUT/stubs" "$OUT/mobile-assets"
